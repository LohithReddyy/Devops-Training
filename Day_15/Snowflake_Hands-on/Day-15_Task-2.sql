

CREATE DATABASE IF NOT EXISTS RETAIL_DB;

SHOW DATABASES LIKE 'RETAIL_DB';



CREATE SCHEMA IF NOT EXISTS RETAIL_DB.RAW;

USE DATABASE RETAIL_DB;

USE SCHEMA RETAIL_DB.RAW;

SHOW SCHEMAS IN DATABASE RETAIL_DB;

SELECT CURRENT_SCHEMA();

CREATE WAREHOUSE IF NOT EXISTS RETAIL_WH
WAREHOUSE_SIZE = 'XSMALL'
AUTO_SUSPEND = 60
AUTO_RESUME = TRUE
INITIALLY_SUSPENDED = TRUE;

USE WAREHOUSE RETAIL_WH;

SHOW WAREHOUSES LIKE 'RETAIL_WH';

SELECT CURRENT_WAREHOUSE();


CREATE TABLE IF NOT EXISTS CUSTOMER_SALES (
    TRANSACTION_ID NUMBER(10,0),
    TRANSACTION_DATE DATE,
    CUSTOMER_ID VARCHAR(50),
    GENDER VARCHAR(20),
    AGE NUMBER(3,0),
    PRODUCT_CATEGORY VARCHAR(100),
    QUANTITY NUMBER(10,0),
    PRICE_PER_UNIT NUMBER(10,2),
    TOTAL_AMOUNT NUMBER(12,2)
);

SHOW TABLES LIKE 'CUSTOMER_SALES'
IN SCHEMA RETAIL_DB.RAW;

DESCRIBE TABLE RETAIL_DB.RAW.CUSTOMER_SALES;


CREATE FILE FORMAT IF NOT EXISTS RETAIL_CSV_FORMAT
TYPE = CSV
SKIP_HEADER = 1
FIELD_OPTIONALLY_ENCLOSED_BY = '"'
EMPTY_FIELD_AS_NULL = TRUE;


SHOW FILE FORMATS IN SCHEMA RETAIL_DB.RAW;


CREATE STAGE IF NOT EXISTS RETAIL_STAGE
FILE_FORMAT = RETAIL_CSV_FORMAT;

SHOW STAGES IN SCHEMA RETAIL_DB.RAW;

LIST @RETAIL_DB.RAW.RETAIL_STAGE;

COPY INTO RETAIL_DB.RAW.CUSTOMER_SALES
FROM @RETAIL_DB.RAW.RETAIL_STAGE
FILE_FORMAT = (
    FORMAT_NAME = 'RETAIL_DB.RAW.RETAIL_CSV_FORMAT'
)
ON_ERROR = 'ABORT_STATEMENT';


SELECT COUNT(*) AS TOTAL_RECORDS
FROM RETAIL_DB.RAW.CUSTOMER_SALES;



SELECT *
FROM RETAIL_DB.RAW.CUSTOMER_SALES
ORDER BY TRANSACTION_ID;


SELECT
    TRANSACTION_ID,
    COUNT(*) AS RECORD_COUNT
FROM RETAIL_DB.RAW.CUSTOMER_SALES
GROUP BY TRANSACTION_ID
HAVING COUNT(*) > 1;



SELECT *
FROM RETAIL_DB.RAW.CUSTOMER_SALES
WHERE TRANSACTION_DATE IS NULL
OR CUSTOMER_ID IS NULL
OR GENDER IS NULL
OR AGE IS NULL
OR PRODUCT_CATEGORY IS NULL
OR QUANTITY IS NULL
OR PRICE_PER_UNIT IS NULL
OR TOTAL_AMOUNT IS NULL;



SELECT *
FROM RETAIL_DB.RAW.CUSTOMER_SALES
WHERE TOTAL_AMOUNT <> QUANTITY * PRICE_PER_UNIT;


SELECT
    COUNT(*) AS TOTAL_RECORDS,
    SUM(QUANTITY) AS TOTAL_QUANTITY,
    AVG(QUANTITY) AS AVG_QUANTITY,
    MIN(QUANTITY) AS MIN_QUANTITY,
    MAX(QUANTITY) AS MAX_QUANTITY,
    MEDIAN(QUANTITY) AS MEDIAN_QUANTITY,
    STDDEV(QUANTITY) AS STDDEV_QUANTITY,
    VARIANCE(QUANTITY) AS VARIANCE_QUANTITY
FROM RETAIL_DB.RAW.CUSTOMER_SALES;



SELECT
    GENDER,
    COUNT(*) AS TOTAL_TRANSACTIONS,
    ROUND(
        COUNT(*) * 100.0 /
        SUM(COUNT(*)) OVER (), 2
    ) AS PERCENTAGE
FROM RETAIL_DB.RAW.CUSTOMER_SALES
GROUP BY GENDER;




SELECT
    PRODUCT_CATEGORY,
    COUNT(*) AS TRANSACTION_COUNT,
    SUM(QUANTITY) AS TOTAL_QUANTITY,
    ROUND(
        COUNT(*) * 100.0 /
        SUM(COUNT(*)) OVER (), 2
    ) AS TRANSACTION_PERCENTAGE
FROM RETAIL_DB.RAW.CUSTOMER_SALES
GROUP BY PRODUCT_CATEGORY
ORDER BY TRANSACTION_COUNT DESC;



SELECT
    CASE
        WHEN AGE BETWEEN 18 AND 25 THEN '18-25'
        WHEN AGE BETWEEN 26 AND 35 THEN '26-35'
        WHEN AGE BETWEEN 36 AND 45 THEN '36-45'
        WHEN AGE BETWEEN 46 AND 55 THEN '46-55'
        ELSE '56+'
    END AS AGE_GROUP,
    COUNT(*) AS CUSTOMER_COUNT,
    AVG(TOTAL_AMOUNT) AS AVG_PURCHASE_AMOUNT
FROM RETAIL_DB.RAW.CUSTOMER_SALES
GROUP BY AGE_GROUP
ORDER BY AGE_GROUP;


WITH QUARTILES AS (
    SELECT
        PERCENTILE_CONT(0.25)
        WITHIN GROUP (ORDER BY TOTAL_AMOUNT) AS Q1,

        PERCENTILE_CONT(0.75)
        WITHIN GROUP (ORDER BY TOTAL_AMOUNT) AS Q3
    FROM RETAIL_DB.RAW.CUSTOMER_SALES
)
SELECT
    Q1,
    Q3,
    Q3 - Q1 AS IQR,
    Q1 - 1.5 * (Q3 - Q1) AS LOWER_BOUND,
    Q3 + 1.5 * (Q3 - Q1) AS UPPER_BOUND
FROM QUARTILES;


SELECT
    CORR(AGE, TOTAL_AMOUNT) AS AGE_AMOUNT_CORRELATION
FROM RETAIL_DB.RAW.CUSTOMER_SALES;


