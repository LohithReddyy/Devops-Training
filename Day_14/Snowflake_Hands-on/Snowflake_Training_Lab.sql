CREATE DATABASE IF NOT EXISTS SALES_DB;

SHOW DATABASES LIKE 'SALES_DB';


CREATE SCHEMA IF NOT EXISTS SALES_DB.STAGING;

USE DATABASE SALES_DB;

USE SCHEMA SALES_DB.STAGING;

SHOW SCHEMAS IN DATABASE SALES_DB;

SELECT CURRENT_SCHEMA();


CREATE WAREHOUSE IF NOT EXISTS SALES_WH
WAREHOUSE_SIZE = 'XSMALL'
AUTO_SUSPEND = 60
AUTO_RESUME = TRUE
INITIALLY_SUSPENDED = TRUE;

USE WAREHOUSE SALES_WH;

SHOW WAREHOUSES LIKE 'SALES_WH';

SELECT CURRENT_WAREHOUSE();


CREATE TABLE IF NOT EXISTS SALES_DATA (
    ORDER_ID NUMBER(10,0),
    ORDER_DATE VARCHAR(20),
    PRODUCT VARCHAR(100),
    QUANTITY VARCHAR(50),
    UNIT_PRICE VARCHAR(50),
    CITY VARCHAR(100)
);

SHOW TABLES LIKE 'SALES_DATA'
IN SCHEMA SALES_DB.STAGING;

DESCRIBE TABLE SALES_DB.STAGING.SALES_DATA;


CREATE FILE FORMAT IF NOT EXISTS SALES_CSV_FORMAT
TYPE = CSV
SKIP_HEADER = 1
FIELD_OPTIONALLY_ENCLOSED_BY = '"'
EMPTY_FIELD_AS_NULL = TRUE;

SHOW FILE FORMATS IN SCHEMA SALES_DB.STAGING;


CREATE STAGE IF NOT EXISTS SALES_STAGE
FILE_FORMAT = SALES_CSV_FORMAT;

SHOW STAGES IN SCHEMA SALES_DB.STAGING;


LIST @SALES_DB.STAGING.SALES_STAGE;


COPY INTO SALES_DB.STAGING.SALES_DATA
FROM @SALES_DB.STAGING.SALES_STAGE
FILE_FORMAT = (
    FORMAT_NAME = 'SALES_DB.STAGING.SALES_CSV_FORMAT'
)
ON_ERROR = 'ABORT_STATEMENT';


SELECT COUNT(*) AS TOTAL_RECORDS
FROM SALES_DB.STAGING.SALES_DATA;


SELECT *
FROM SALES_DB.STAGING.SALES_DATA
ORDER BY ORDER_ID;


SELECT
    ORDER_ID,
    COUNT(*) AS RECORD_COUNT
FROM SALES_DB.STAGING.SALES_DATA
GROUP BY ORDER_ID
HAVING COUNT(*) > 1;


SELECT *
FROM SALES_DB.STAGING.SALES_DATA
WHERE ORDER_DATE IS NULL
OR PRODUCT IS NULL
OR QUANTITY IS NULL
OR UNIT_PRICE IS NULL
OR CITY IS NULL;


SELECT *
FROM SALES_DB.STAGING.SALES_DATA
WHERE TRY_TO_NUMBER(QUANTITY) IS NULL;


SELECT *
FROM SALES_DB.STAGING.SALES_DATA
WHERE TRY_TO_NUMBER(QUANTITY) <= 0;


SELECT *
FROM SALES_DB.STAGING.SALES_DATA
WHERE TRY_TO_DECIMAL(UNIT_PRICE, 12, 2) IS NULL;