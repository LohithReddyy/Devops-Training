SELECT
    CUSTOMER_ID,
    COALESCE(
        NULLIF(TRIM(CUSTOMER_NAME), ''),
        'Unknown'
    ) AS CUSTOMER_NAME,
    LOWER(TRIM(EMAIL)) AS EMAIL,
    UPPER(TRIM(CITY)) AS CITY,
    UPPER(TRIM(STATE)) AS STATE,
    SIGNUP_DATE
FROM CUSTOMERS;


SELECT
    ORDER_ID,
    CUSTOMER_ID,
    ORDER_DATE,
    INITCAP(TRIM(ORDER_STATUS)) AS ORDER_STATUS,
    INITCAP(TRIM(PAYMENT_METHOD)) AS PAYMENT_METHOD
FROM ORDERS;

SELECT
    ORDER_ITEM_ID,
    ORDER_ID,
    INITCAP(TRIM(PRODUCT_NAME)) AS PRODUCT_NAME,
    INITCAP(TRIM(CATEGORY)) AS CATEGORY,
    UNIT_PRICE,
    QUANTITY,
    UNIT_PRICE * QUANTITY AS TOTAL_SALES
FROM ORDER_ITEMS;


SELECT O.*
FROM ECOMMERCE_DB.RAW.ORDERS O
LEFT JOIN ECOMMERCE_DB.RAW.CUSTOMERS C
    ON O.CUSTOMER_ID = C.CUSTOMER_ID
WHERE C.CUSTOMER_ID IS NULL;

SELECT I.*
FROM ECOMMERCE_DB.RAW.ORDER_ITEMS I
LEFT JOIN ECOMMERCE_DB.RAW.ORDERS O
    ON I.ORDER_ID = O.ORDER_ID
WHERE O.ORDER_ID IS NULL;

CREATE OR REPLACE VIEW
ECOMMERCE_DB.RAW.CLEAN_CUSTOMERS AS

SELECT
    CUSTOMER_ID,

    COALESCE(
        NULLIF(TRIM(CUSTOMER_NAME), ''),
        'Unknown'
    ) AS CUSTOMER_NAME,

    LOWER(TRIM(EMAIL)) AS EMAIL,

    UPPER(TRIM(CITY)) AS CITY,

    UPPER(TRIM(STATE)) AS STATE,

    SIGNUP_DATE

FROM ECOMMERCE_DB.RAW.CUSTOMERS;


SELECT
    O.ORDER_ID,
    C.CUSTOMER_ID,
    C.CUSTOMER_NAME,
    C.CITY,
    C.STATE,
    O.ORDER_DATE,
    O.ORDER_STATUS
FROM ECOMMERCE_DB.RAW.ORDERS O
INNER JOIN ECOMMERCE_DB.RAW.CLEAN_CUSTOMERS C
    ON O.CUSTOMER_ID = C.CUSTOMER_ID
WHERE C.CITY = 'CHENNAI';


SELECT
    SUM(UNIT_PRICE * QUANTITY) AS TOTAL_SALES
FROM ECOMMERCE_DB.RAW.ORDER_ITEMS;


SELECT
    PRODUCT_NAME,
    SUM(QUANTITY) AS TOTAL_QUANTITY,
    SUM(UNIT_PRICE * QUANTITY) AS PRODUCT_SALES
FROM ECOMMERCE_DB.RAW.ORDER_ITEMS
GROUP BY PRODUCT_NAME
ORDER BY PRODUCT_SALES DESC;


SELECT
    O.ORDER_ID,
    C.CUSTOMER_ID,
    C.CUSTOMER_NAME,
    C.EMAIL,
    C.CITY,
    O.ORDER_DATE,
    O.ORDER_STATUS,
    O.PAYMENT_METHOD
FROM ECOMMERCE_DB.RAW.ORDERS O
INNER JOIN ECOMMERCE_DB.RAW.CLEAN_CUSTOMERS C
    ON O.CUSTOMER_ID = C.CUSTOMER_ID
ORDER BY O.ORDER_DATE;


SELECT
    C.CUSTOMER_ID,
    C.CUSTOMER_NAME,
    COUNT(DISTINCT O.ORDER_ID) AS TOTAL_ORDERS,
    SUM(I.UNIT_PRICE * I.QUANTITY) AS TOTAL_SALES
FROM ECOMMERCE_DB.RAW.CLEAN_CUSTOMERS C
INNER JOIN ECOMMERCE_DB.RAW.ORDERS O
    ON C.CUSTOMER_ID = O.CUSTOMER_ID
INNER JOIN ECOMMERCE_DB.RAW.ORDER_ITEMS I
    ON O.ORDER_ID = I.ORDER_ID
GROUP BY
    C.CUSTOMER_ID,
    C.CUSTOMER_NAME
ORDER BY TOTAL_SALES DESC;


SELECT
    PRODUCT_NAME,
    CATEGORY,
    SUM(UNIT_PRICE * QUANTITY) AS TOTAL_SALES
FROM ECOMMERCE_DB.RAW.ORDER_ITEMS
GROUP BY
    PRODUCT_NAME,
    CATEGORY
ORDER BY TOTAL_SALES DESC;