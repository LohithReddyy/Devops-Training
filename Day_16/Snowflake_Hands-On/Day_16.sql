SHOW DATABASES;
SHOW WAREHOUSES;


CREATE DATABASE IF NOT EXISTS ECOMMERCE_DB;

CREATE WAREHOUSE IF NOT EXISTS ECOMMERCE_WH
WITH
    WAREHOUSE_SIZE = 'X-SMALL'
    AUTO_SUSPEND = 60
    AUTO_RESUME = TRUE
    INITIALLY_SUSPENDED = TRUE;

    USE WAREHOUSE ECOMMERCE_WH;
    USE DATABASE ECOMMERCE_DB;

    CREATE SCHEMA IF NOT EXISTS RAW;

    USE SCHEMA RAW;

    SHOW WAREHOUSES LIKE 'ECOMMERCE_WH';

    SHOW SCHEMAS IN DATABASE ECOMMERCE_DB;


    CREATE TABLE IF NOT EXISTS CUSTOMERS (
    CUSTOMER_ID NUMBER PRIMARY KEY,
    CUSTOMER_NAME VARCHAR(100),
    EMAIL VARCHAR(150),
    CITY VARCHAR(100),
    STATE VARCHAR(100),
    SIGNUP_DATE DATE
);


CREATE TABLE IF NOT EXISTS ORDERS (
    ORDER_ID NUMBER PRIMARY KEY,
    CUSTOMER_ID NUMBER,
    ORDER_DATE DATE,
    ORDER_STATUS VARCHAR(50),
    PAYMENT_METHOD VARCHAR(50)
);


CREATE TABLE IF NOT EXISTS ORDER_ITEMS (
    ORDER_ITEM_ID NUMBER PRIMARY KEY,
    ORDER_ID NUMBER,
    PRODUCT_NAME VARCHAR(150),
    CATEGORY VARCHAR(100),
    UNIT_PRICE NUMBER(10,2),
    QUANTITY NUMBER
);

SHOW TABLES IN SCHEMA ECOMMERCE_DB.RAW;

DESC TABLE CUSTOMERS;

DESC TABLE ORDERS;

DESC TABLE ORDER_ITEMS;


CREATE OR REPLACE FILE FORMAT ECOMMERCE_CSV_FORMAT
TYPE = 'CSV'
FIELD_DELIMITER = ','
SKIP_HEADER = 1
FIELD_OPTIONALLY_ENCLOSED_BY = '"'
TRIM_SPACE = TRUE
EMPTY_FIELD_AS_NULL = TRUE
NULL_IF = ('NULL', 'null');


CREATE OR REPLACE STAGE ECOMMERCE_STAGE
FILE_FORMAT = (
    FORMAT_NAME = ECOMMERCE_CSV_FORMAT
);

SHOW STAGES IN SCHEMA ECOMMERCE_DB.RAW;

LIST @ECOMMERCE_STAGE;


COPY INTO CUSTOMERS
FROM @ECOMMERCE_STAGE
FILES = ('Customers.csv')
FILE_FORMAT = (
    FORMAT_NAME = ECOMMERCE_CSV_FORMAT
)
ON_ERROR = 'ABORT_STATEMENT';

COPY INTO ORDERS
FROM @ECOMMERCE_STAGE
FILES = ('Orders.csv')
FILE_FORMAT = (
    FORMAT_NAME = ECOMMERCE_CSV_FORMAT
)
ON_ERROR = 'ABORT_STATEMENT';


COPY INTO ORDER_ITEMS
FROM @ECOMMERCE_STAGE
FILES = ('OrderItems.csv')
FILE_FORMAT = (
    FORMAT_NAME = ECOMMERCE_CSV_FORMAT
)
ON_ERROR = 'ABORT_STATEMENT';

